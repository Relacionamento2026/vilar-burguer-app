import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const index=read('index.html'),app=read('app.js'),admin=read('admin.html'),adminJs=read('admin.js'),config=read('config.js');
new Script(app,{filename:'app.js'});new Script(adminJs,{filename:'admin.js'});new Script(config,{filename:'config.js'});
for(const id of ['catalog','cartDrawer','checkoutForm','storeStatus','itemModal','cartItems','cartTotal','sendOrder','clientName','clientPhone','street','neighborhood','city','payment'])assert(index.includes('id="'+id+'"'),'Missing public element '+id);
for(const id of ['loginForm','signupBtn','adminContent','editDialog','settingsForm']){if(id==='settingsForm')assert(adminJs.includes(id));else assert(admin.includes('id="'+id+'"'),'Missing admin element '+id);}
for(const name of ['app.js','config.js','manifest.webmanifest','admin.html','privacidade.html'])assert(index.includes(name),'Missing reference '+name);
assert(!config.includes('service_role'),'Never publish a service role key in frontend');
const manifest=JSON.parse(read('manifest.webmanifest'));
assert(manifest.name.includes('Vilar Burguer'));assert(manifest.display==='standalone');
const edge=read('supabase/functions/submit-order/index.ts');
for(const value of ['SERVICE_ROLE_KEY','subtotal_cents','idempotency_key','delivery_fee_cents'])assert(edge.includes(value),'Missing backend control '+value);
const tracking=read('acompanhar.html');
const start=tracking.lastIndexOf('<script>'),end=tracking.lastIndexOf('</script>');
assert(start>=0&&end>start,'Tracking page must have a script');
new Script(tracking.slice(start+8,end),{filename:'acompanhar.html'});
assert(tracking.includes('content="no-referrer"'),'Tracking links must not leak in referrer');
assert(tracking.includes('order-status?token='),'Tracking must fetch private-token API');
assert(index.includes('href="./acompanhar.html"'),'Tracking page must be linked');
assert(app.includes('settings.payment_gateway_ready===true'),'Checkout must require ready payment gateway');
assert(!app.includes('fetch(CONFIG.checkoutFunction'),'Public checkout must not submit before Pix integration');
assert(edge.includes('BLOQUEIO COMERCIAL')&&edge.includes('return reply(503'),'Backend must block unpaid checkout');
const statusApi=read('supabase/functions/order-status/index.ts');
assert(statusApi.includes('tracking_token=eq.'),'Tracking must require secret token');
assert(!statusApi.includes('customer_phone')&&!statusApi.includes('customer_name'),'Tracking API must not expose PII');
assert(adminJs.includes('nextStatuses')&&adminJs.includes('o.payment_status!=="paid"'),'Admin statuses must require Pix');
assert(adminJs.includes('data-wa-status'),'Admin should be able to share status manually');
console.log('✓ Pix obrigatório, acompanhamento, segurança e sintaxe verificados.');

